package com.andrei1058.bedwars.listeners;

import com.andrei1058.bedwars.BedWars;
import com.andrei1058.bedwars.arena.Arena;
import org.bukkit.Bukkit;
import org.bukkit.Chunk;
import org.bukkit.Material;
import org.bukkit.World;
import org.bukkit.entity.Entity;
import org.bukkit.entity.EntityType;
import org.bukkit.event.EventHandler;
import org.bukkit.event.EventPriority;
import org.bukkit.event.Listener;
import org.bukkit.event.world.ChunkLoadEvent;

import java.lang.reflect.Method;
import java.util.HashSet;
import java.util.Set;

/**
 * Safety net: arena maps are void outside the area that was built. If a world of an arena ends up with a vanilla
 * chunk generator anyway (a restore adapter that did not pass the void generator, a stale world folder...), every
 * chunk that has to be generated is emptied again instead of showing vanilla terrain around the map.
 * Chunks that come from the map files are never touched.
 */
public class VoidGuardListener implements Listener {

    private final Set<String> warned = new HashSet<>();
    private Method minHeight;

    @EventHandler(priority = EventPriority.LOWEST)
    public void onChunkLoad(ChunkLoadEvent e) {
        if (!e.isNewChunk()) return;
        World world = e.getWorld();
        if (world.getGenerator() != null) return; // generated by a void generator already
        if (Arena.getArenaByIdentifier(world.getName()) == null) return;

        if (warned.add(world.getName())) {
            BedWars.plugin.getLogger().warning("The world of arena '" + world.getName() + "' uses the vanilla chunk generator. " +
                    "Chunks outside the map are emptied to keep it void; check which plugin creates the world without the void generator.");
        }
        clear(e.getChunk());
    }

    private void clear(Chunk chunk) {
        World world = chunk.getWorld();
        int min = 0;
        try {
            if (minHeight == null) minHeight = World.class.getMethod("getMinHeight");
            min = (Integer) minHeight.invoke(world);
        } catch (Throwable ignored) {
            // old API: worlds start at 0
        }
        int max = world.getMaxHeight();
        for (int x = 0; x < 16; x++) {
            for (int z = 0; z < 16; z++) {
                for (int y = max - 1; y >= min; y--) {
                    org.bukkit.block.Block b = chunk.getBlock(x, y, z);
                    if (b.getType() != Material.AIR) b.setType(Material.AIR, false);
                }
            }
        }
        for (Entity en : chunk.getEntities()) {
            if (en.getType() != EntityType.PLAYER) en.remove();
        }
    }
}
